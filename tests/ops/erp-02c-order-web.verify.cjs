'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { createBusinessPool } = require('../../backend/business-db/connection');
const { createPartnerService } = require('../../backend/modules/partners/service');
const { createOrderService } = require('../../backend/modules/orders/service');
const { createInventoryService } = require('../../backend/modules/inventory/service');
async function main() {
  if (!process.argv[2] || !process.env.ERP_02C_PLAYWRIGHT_MODULE || !process.env.ERP_02C_BROWSER_EXECUTABLE) throw new Error('Explicit isolated config and headless browser required');
  const config = JSON.parse((await fs.readFile(process.argv[2], 'utf8')).replace(/^\uFEFF/, ''));
  const url = new URL(config.connectionString);
  if (url.hostname !== '127.0.0.1' || url.pathname !== '/erp_02c_acceptance') throw new Error('Not an isolated UI database');
  const directory = path.dirname(path.resolve(process.argv[2]));
  const pool = await createBusinessPool({ connectionString: config.connectionString });
  let browser, page;
  const checks = [], errors = [];
  await fs.writeFile(path.join(directory, 'order-web-verification.json'), JSON.stringify({ result: 'running' }));
  try {
    assert.equal((await pool.query("SELECT server_id FROM erp.installation WHERE id='default'")).rows[0].server_id, '02c00000-0000-4000-8000-000000000001');
    const { chromium } = require(process.env.ERP_02C_PLAYWRIGHT_MODULE);
    browser = await chromium.launch({ headless: true, executablePath: process.env.ERP_02C_BROWSER_EXECUTABLE });
    page = await browser.newPage({ viewport: { width: 1366, height: 900 } });
    page.on('pageerror', error => errors.push(error.message));
    const suffix = Date.now().toString(36);
    let sequence = 0;
    const actor = { actorId: 'owner', tokenVersion: '1' };
    const customers = createPartnerService(pool, 'customers');
    const orders = createOrderService(pool, { uploadDirectory: path.join(directory, 'uploads') });
    const command = (service, operation, payload) => service.execute({ ...actor, operation, payload, key: `order-ui-${suffix}-${++sequence}` });
    const customerA = (await command(customers, 'customer.create', { code: `OA-${suffix}`, name: '同名验收客户', phone: '13800000101' })).body;
    let customerB = (await command(customers, 'customer.create', { code: `OB-${suffix}`, name: '同名验收客户', phone: '13800000102' })).body;
    const field = label => page.getByText(label, { exact: true }).filter({ visible: true }).locator('..').locator('input,textarea');
    const button = title => page.getByRole('button', { name: title, exact: true });
    const choose = async (label, option) => {
      await page.getByText(label, { exact: true }).filter({ visible: true }).locator('..').locator('[tabindex="0"]').first().click();
      await page.getByText(option, { exact: true }).filter({ visible: true }).last().click();
    };
    const edit = async () => { await button('编辑订单').click(); await button('保存修改').waitFor(); };
    const detail = () => button('编辑订单').waitFor();
    const origin = `http://127.0.0.1:${config.port}`;
    await page.goto(origin);
    await page.getByPlaceholder('例如 192.168.1.10:5000').fill(origin + '/api');
    await button('测试并保存').click();
    await page.getByPlaceholder('请输入邮箱').fill('owner@erp-02c.example.test');
    await page.getByPlaceholder('请输入密码').fill(config.password);
    await button('登录').click();
    await page.getByRole('tab', { name: '订单', exact: true }).click();
    await button('新建订单').first().click();
    await button('保存订单').click();
    await page.getByText('请从客户档案中选择客户', { exact: true }).waitFor();
    checks.push('未选择客户不能保存订单');
    await choose('客户 *', `${customerB.code} · 同名验收客户 · ${customerB.phone}`);
    await choose('模型 *', '验收模型');
    await choose('材质', 'PLA');
    await field('颜色').fill('白色');
    await field('数量 *').fill('0.001');
    await field('单价（元）*').fill('5');
    const marker = `订单页面验收-${suffix}`;
    await field('订单备注').fill(marker);
    await page.getByText('订单合计：¥0.01', { exact: true }).waitFor();
    let dropped = false;
    const creationRequests = [];
    await page.route('**/api/orders', async route => {
      if (route.request().method() !== 'POST') return route.continue();
      creationRequests.push({ key: route.request().headers()['idempotency-key'], version: route.request().headers()['x-business-rules-version'], body: route.request().postDataJSON() });
      if (!dropped) { dropped = true; const response = await route.fetch(); assert.equal(response.status(), 201); return route.abort('failed'); }
      return route.continue();
    });
    await button('保存订单').click();
    await button('重试原操作').waitFor();
    assert.equal(await field('数量 *').isEditable(), false);
    await button('重试原操作').click();
    await detail();
    assert.equal(creationRequests.length, 2);
    assert.equal(creationRequests[0].key, creationRequests[1].key);
    assert.equal(creationRequests[0].version, '2');
    assert.equal(creationRequests[0].body.customerId, customerB.id);
    assert.equal(creationRequests[0].body.items[0].quantity, '0.001');
    assert.equal(Object.hasOwn(creationRequests[0].body, 'total'), false);
    assert.equal(Object.hasOwn(creationRequests[0].body.items[0], 'subtotal'), false);
    const ids = (await pool.query('SELECT id FROM erp.orders WHERE notes=$1', [marker])).rows;
    assert.equal(ids.length, 1);
    const id = ids[0].id;
    let order = await orders.get(actor, id);
    assert.equal(order.total, '0.01'); assert.equal(order.customerId, customerB.id);
    const lineId = order.items[0].id;
    checks.push('同名客户按编号选中正确 ID，逐行取整及结果未知重试不重复建单');
    customerB = (await command(customers, 'customer.update', { id: customerB.id, version: customerB.version, changes: { name: '档案新名称', phone: '13800000199' } })).body;
    await edit();
    await page.getByText('订单原客户：同名验收客户 · 13800000102', { exact: true }).waitFor();
    await field('订单备注').fill('未保存的输入');
    await button('核对客户最新资料').click();
    await page.getByText('请先保存当前修改，再核对客户最新资料', { exact: true }).waitFor();
    assert.equal(await field('订单备注').inputValue(), '未保存的输入');
    await field('订单备注').fill(marker);
    await button('核对客户最新资料').click();
    await page.getByText('档案最新资料：档案新名称 · 13800000199 · 未填写邮箱', { exact: true }).waitFor();
    await button('确认更新订单客户资料').click();
    await page.getByText('订单原客户：档案新名称 · 13800000199', { exact: true }).waitFor();
    order = await orders.get(actor, id);
    assert.equal(order.customer.name, '档案新名称'); assert.equal(order.items[0].id, lineId);
    checks.push('客户改名不会自动改订单，刷新前保护未保存输入，明确确认才更新快照');
    await choose('客户 *', `${customerA.code} · 同名验收客户 · ${customerA.phone}`);
    await button('保存修改').click();
    await detail();
    order = await orders.get(actor, id);
    assert.equal(order.customerId, customerA.id); assert.equal(order.customer.phone, customerA.phone);
    assert.equal(order.items[0].id, lineId); assert.equal(order.total, '0.01');
    checks.push('显式换客户只更新客户关系及快照，订单行和金额保留');
    const inactive = (await command(customers, 'customer.setActive', { id: customerA.id, version: customerA.version, active: false })).body;
    await command(customers, 'customer.update', { id: inactive.id, version: inactive.version, changes: { name: '停用后改名' } });
    await edit();
    await page.getByText(`订单原客户：同名验收客户 · ${customerA.phone}`, { exact: true }).waitFor();
    await field('订单备注').fill(`${marker}-保留停用客户`);
    await button('保存修改').click(); await detail();
    order = await orders.get(actor, id);
    assert.equal(order.customer.name, '同名验收客户'); assert.equal(order.customerId, customerA.id);
    checks.push('停用客户仍可保留旧订单原值并修改说明');
    const filename = `order-${suffix}.pdf`;
    const bytes = 'isolated attachment proof';
    await fs.writeFile(path.join(directory, 'uploads', filename), bytes);
    order = (await command(orders, 'order.attachment.add', { id, version: order.version, file: { fileKey: filename, name: '历史附件.pdf' } })).body;
    order = (await command(orders, 'order.transition', { id, version: order.version, status: 'in_progress' })).body;
    // Deliberately inconsistent legacy pricing is retained by description-only edits.
    await pool.query("UPDATE erp.orders SET total=9007199254740993.01 WHERE id=$1", [id]);
    await pool.query(`UPDATE erp.order_items SET model_id=NULL,subtotal=9007199254740993.01,
      spec_snapshot=spec_snapshot||'{"modelId":"removed-model","unknown":9007199254740993.01,"layerHeightMm":"-1","externalFileUrl":"old-scheme:preserved"}'::jsonb WHERE order_id=$1`, [id]);
    await pool.query(`UPDATE erp.order_attachments SET metadata=metadata||'{"unknown":9007199254740993.01}'::jsonb WHERE order_id=$1`, [id]);
    await edit();
    assert.equal(await field('数量 *').isEditable(), false);
    assert.equal(await field('单价（元）*').isEditable(), false);
    await page.getByText('订单合计：¥9007199254740993.01', { exact: true }).waitFor();
    await page.getByText('历史附件.pdf', { exact: true }).waitFor();
    await field('订单备注').fill('');
    await field('项目说明').fill('执行中补充说明');
    await page.getByLabel('截止日期', { exact: true }).fill('2026-12-25');
    await button('保存修改').click(); await detail();
    order = await orders.get(actor, id);
    assert.equal(order.notes, ''); assert.equal(order.items[0].notes, '执行中补充说明');
    assert.equal(order.dueDate, '2026-12-25');
    assert.equal(order.items[0].id, lineId); assert.equal(order.total, '9007199254740993.01');
    assert.equal(order.items[0].subtotal, '9007199254740993.01');
    assert.equal(order.items[0].unknown, '9007199254740993.01');
    assert.equal(order.items[0].layerHeightMm, '-1');
    assert.equal(order.attachments.length, 1); assert.equal(order.attachments[0].unknown, '9007199254740993.01');
    assert.equal(await fs.readFile(path.join(directory, 'uploads', filename), 'utf8'), bytes);
    assert.ok((await page.locator('body').innerText()).includes('CNY 9007199254740993.01'));
    await page.screenshot({ path: path.join(directory, 'order-exact-details.png') });
    checks.push('执行中仅改交期/说明，精确历史金额、已删除模型引用、未知规格及附件实物保留');
    await edit();
    await field('订单备注').fill('冲突后保留输入');
    order = await orders.get(actor, id);
    await command(orders, 'order.update', { id, version: order.version, changes: { notes: '其他人最新修改' } });
    await button('保存修改').click();
    await button('重新加载最新订单（替换当前输入）').waitFor();
    assert.equal(await field('订单备注').inputValue(), '冲突后保留输入');
    await button('重新加载最新订单（替换当前输入）').click();
    await page.waitForFunction(() => [...document.querySelectorAll('textarea')].some(input => input.value === '其他人最新修改'));
    await page.setViewportSize({ width: 390, height: 844 });
    await field('项目说明').scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.screenshot({ path: path.join(directory, 'order-edit-narrow.png') });
    checks.push('版本冲突保留输入并明确重载，窄屏可滚动且无水平溢出');
    order = await orders.get(actor, id);
    await command(orders, 'order.transition', { id, version: order.version, status: 'draft' });
    const inventory = createInventoryService(pool);
    const lot = (await command(inventory, 'lot.create', { materialId: 'material-a', qty_g: '1' })).body;
    await command(inventory, 'inventory.post', { lotId: lot.id, type: 'out', qty_g: '0.001', orderId: id });
    assert.equal((await orders.get(actor, id)).commercialEditable, false);
    await button('返回').click(); await detail();
    await edit();
    await page.getByText('状态：草稿', { exact: true }).waitFor();
    assert.equal(await field('数量 *').isEditable(), false);
    assert.equal(await field('单价（元）*').isEditable(), false);
    assert.equal(await button('核对客户最新资料').count(), 0);
    await field('订单备注').fill('已有库存记录仍只改说明');
    await button('保存修改').click(); await detail();
    assert.equal((await orders.get(actor, id)).notes, '已有库存记录仍只改说明');
    assert.equal((await orders.get(actor, id)).total, '9007199254740993.01');
    checks.push('已有库存流水的订单恢复草稿后仍锁定商业字段，说明维护正常');
    assert.deepEqual(errors, []);
    await fs.writeFile(path.join(directory, 'order-web-verification.json'), JSON.stringify({ result: 'passed', utcTimestamp: new Date().toISOString(), checks, pageErrors: errors, productionUsed: false }, null, 2));
    console.log(JSON.stringify({ result: 'passed', checks: checks.length, pageErrors: errors.length }));
  } catch (error) {
    if (page && !page.isClosed()) { await page.screenshot({ path: path.join(directory, 'order-web-failure.png') }); console.error('Visible UI:', (await page.locator('body').innerText()).slice(-5000)); }
    await fs.writeFile(path.join(directory, 'order-web-verification.json'), JSON.stringify({ result: 'failed', utcTimestamp: new Date().toISOString(), checks, pageErrors: errors, error: error.message, productionUsed: false }, null, 2));
    throw error;
  } finally { try { if (browser) await browser.close(); } finally { await pool.end(); } }
}
main().catch(error => { console.error(error.stack); process.exitCode = 1; });
